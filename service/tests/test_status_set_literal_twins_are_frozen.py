IN_LIST = re.compile(r"\bIN\s*\(\s*((?:'[^']*'\s*,\s*)+'[^']*')\s*\)", re.IGNORECASE)


def _sources() -> list[tuple[str, str]]:
    out = []
    for path in sorted((REPO / "service").rglob("*.py")):
        rel = path.relative_to(REPO)
        if PRUNE & set(rel.parts):
            continue
        out.append((rel.as_posix(), path.read_text(encoding="utf-8")))
    return out


def _named_sets(sources) -> dict[str, tuple[frozenset, str]]:
    """Module-level assignments of a small set/list/tuple of plain strings."""
    found: dict[str, tuple[frozenset, str]] = {}
    for rel, src in sources:
        try:
            tree = ast.parse(src)
        except SyntaxError:
            continue
        for node in tree.body:
            if not isinstance(node, ast.Assign) or len(node.targets) != 1:
                continue
            target = node.targets[0]
            if not isinstance(target, ast.Name):
                continue
            value = node.value
            if isinstance(value, ast.Call) and getattr(value.func, "id", "") == "frozenset" and value.args:
                value = value.args[0]
            if not isinstance(value, (ast.Set, ast.List, ast.Tuple)):
                continue
            items = []
            for elt in value.elts:
                if isinstance(elt, ast.Constant) and isinstance(elt.value, str):
                    items.append(elt.value)
                else:
                    break
            else:
                if 2 <= len(items) <= 12:
                    found[target.id] = (frozenset(items), rel)
    return found


def _literal_twins(sources, named) -> dict[str, set]:
    """Files whose SQL spells out a set exactly matching exactly ONE named constant."""
    by_values: dict[frozenset, list] = {}
    for name, (values, _owner) in named.items():
        by_values.setdefault(values, []).append(name)
    twins: dict[str, set] = {}
    for rel, src in sources:
        for match in IN_LIST.finditer(src):
            values = frozenset(v.strip().strip("'") for v in match.group(1).split(","))
            owners = by_values.get(values)
            if not owners or len(owners) != 1:
                continue  # ambiguous ownership is out of scope; see the module docstring
            twins.setdefault(owners[0], set()).add(rel)
    return twins


class StatusSetLiteralTwinsTests(unittest.TestCase):
    def test_each_constant_still_holds_the_values_its_twins_assume(self):
        """THE ONE THAT MATTERS. Change a canonical set and the hardcoded copies keep the OLD
        meaning, silently, in every file listed. This turns that into a failure that names them."""
        named = _named_sets(_sources())
        for name, entry in FROZEN.items():
            with self.subTest(constant=name):
                self.assertIn(name, named, f"{name} is gone; the SQL twins below now copy nothing")
                values, owner = named[name]
                self.assertEqual(owner, entry["owner"], f"{name} moved; update the ledger")
                self.assertEqual(
                    sorted(values), entry["values"],
                    f"{name} changed. Every one of these files spells the OLD values out in SQL and "
                    f"will keep the old meaning until updated with it: {entry['hardcoded_in']}",
                )

    def test_no_new_file_starts_spelling_a_constant_out(self):
        sources = _sources()
        actual = _literal_twins(sources, _named_sets(sources))
        for name, entry in FROZEN.items():
            with self.subTest(constant=name):
                self.assertEqual(
                    sorted(actual.get(name, set())), entry["hardcoded_in"],
                    f"the files hardcoding {name} changed. FEWER is good -- a query now uses the "
                    f"constant, so shrink this list. MORE means a new copy that will not move when "
                    f"the constant does.",
                )

    def test_the_scanner_is_not_silently_matching_nothing(self):
        sources = _sources()
        named = _named_sets(sources)
        self.assertGreater(len(named), 10, "the named-set scan found almost nothing")
        twins = _literal_twins(sources, named)
        self.assertEqual(sorted(twins), sorted(FROZEN), "the constant list itself drifted")
        self.assertGreaterEqual(sum(len(v) for v in twins.values()), 20)

    def test_the_twin_detector_fires_on_a_fixture(self):
        fixture = [("service/fake.py", "Q = \"SELECT 1 WHERE s IN ('a','b')\"\n")]
        named = {"FAKE_SET": (frozenset({"a", "b"}), "service/fake.py")}
        self.assertEqual(_literal_twins(fixture, named), {"FAKE_SET": {"service/fake.py"}})
        self.assertEqual(
            _literal_twins([("x.py", "s IN ('a','c')")], named), {},
            "a different value set must not be attributed to that constant",
        )
