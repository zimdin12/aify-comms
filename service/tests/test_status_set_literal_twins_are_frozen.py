"""A canonical status set, and the SQL literals that spell it out again.

`LIVE_SESSION_STATUSES` names the session statuses meaning "this session is live". Eleven queries do
not use it — they write the six strings out inside their SQL. `_DISPATCH_TERMINAL_STATUSES` has five
such twins, and three more constants have one to three each: 22 files, 5 constants.

THIS REPO HAS ALREADY PAID FOR THIS EXACT BUG. From the frozen pre-split `control_agent` fixture:

    ALLOWLIST, never a blocklist (fixed 2026-07-26). This gate used to be
    `status NOT IN ('stopped','failed','ended','cancelled')`, which silently treats every status NOT
    on that list as LIVE. `lost` is not on it — so an agent whose worker was lost months ago read as
    "already running" forever ... Live-reproduced on the whole ef- team (four sessions stuck `lost`
    with ended_at 2026-04-30), which were permanently unstartable from the dashboard.

The fix at that site says: "Use the canonical live sets instead, so a new session status can never
silently mean 'live' here again." It was applied to ONE gate. Twenty-two other files still spell the
sets out, and nothing connects them to the constants they copy.

WHAT THIS GATE IS FOR, and it is not tidiness. Add a status to a canonical set and every hardcoded
twin silently keeps the old meaning — the same shape as the incident, in twenty-two places. So it
asserts the CONSTANT'S VALUE against the ledger: change the constant and this fails, naming every
file whose SQL must change with it. That is the failure the `lost` incident needed and did not have.

IT RULES NOTHING ELSE. Repointing twenty-two queries at their constants is a real refactor with real
risk — several are hot liveness queries — and which of them SHOULD share an owner is a reviewer's
call. Four differently-named constants hold identical values, so nine further literals cannot be
attributed to one owner at all and are deliberately out of scope. Freezing today's population stops
it growing while that stays open.
"""

